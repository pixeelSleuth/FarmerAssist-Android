import firebase_admin

from firebase_admin import credentials
from firebase_admin import auth

from app.core.config import settings

cred = credentials.Certificate(
    settings.FIREBASE_CREDENTIALS
)

firebase_admin.initialize_app(cred)


def verify_firebase_token(token: str):
    """
    Verify Firebase token. Supports both ID tokens and custom tokens.
    - ID tokens: Generated by Firebase Auth (client login)
    - Custom tokens: Generated by server (for testing/server-to-server)
    """
    
    try:
        # Try to verify as ID token first (standard client auth)
        decoded_token = auth.verify_id_token(token)
        return decoded_token
    except auth.InvalidIdTokenError:
        # If it's not an ID token, try as custom token (server-generated for testing)
        try:
            decoded_token = auth.verify_custom_token(token)
            return decoded_token
        except Exception as e:
            raise ValueError(f"Invalid token: {str(e)}")